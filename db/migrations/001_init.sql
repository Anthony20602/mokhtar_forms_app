-- Mokhtar Forms: initial schema

-- Arabic-insensitive search key: drops diacritics/tatweel and unifies letter
-- variants (أ إ آ ٱ -> ا, ة -> ه, ى -> ي, ؤ -> و, ئ -> ي).
-- Keep in sync with normalizeAr() in src/lib/arabic.ts.
CREATE OR REPLACE FUNCTION normalize_ar(t text) RETURNS text
LANGUAGE sql IMMUTABLE PARALLEL SAFE RETURNS NULL ON NULL INPUT AS $fn$
  SELECT btrim(regexp_replace(
    translate(
      lower(t),
      U&'\0623\0625\0622\0671\0629\0649\0624\0626\064B\064C\064D\064E\064F\0650\0651\0652\0653\0654\0655\0670\0640',
      U&'\0627\0627\0627\0627\0647\064A\0648\064A'
    ),
    '\s+', ' ', 'g'))
$fn$;

CREATE TABLE persons (
  id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- Registry (سجل) number. Text on purpose: the registry has values like "17 مكرر".
  record_no         text NOT NULL DEFAULT '',
  family_name       text NOT NULL DEFAULT '',
  first_name        text NOT NULL DEFAULT '',
  father_name       text NOT NULL DEFAULT '',
  mother_name       text NOT NULL DEFAULT '',
  -- Kept as written in the registry: "26/5/1994" or just "1970".
  birth_date        text NOT NULL DEFAULT '',
  gender            text NOT NULL DEFAULT '',
  personal_religion text NOT NULL DEFAULT '',
  record_religion   text NOT NULL DEFAULT '',
  notes             text NOT NULL DEFAULT '',
  search_text       text GENERATED ALWAYS AS (
    normalize_ar(first_name || ' ' || father_name || ' ' || family_name || ' ' || mother_name)
  ) STORED,
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX persons_record_no_idx ON persons (record_no);
CREATE INDEX persons_name_idx ON persons (family_name, first_name, father_name);

-- Every form that was filled in / printed.
CREATE TABLE documents (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  form_type       text NOT NULL,
  person_id       integer REFERENCES persons (id) ON DELETE SET NULL,
  person_name     text NOT NULL DEFAULT '',
  serial_year     integer NOT NULL,
  serial_no       integer NOT NULL,
  data            jsonb NOT NULL DEFAULT '{}'::jsonb,
  print_count     integer NOT NULL DEFAULT 0,
  last_printed_at timestamptz,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  UNIQUE (serial_year, serial_no)
);

CREATE INDEX documents_person_idx ON documents (person_id, created_at DESC);
CREATE INDEX documents_created_idx ON documents (created_at DESC);

CREATE TABLE settings (
  key        text PRIMARY KEY,
  value      jsonb NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now()
);
